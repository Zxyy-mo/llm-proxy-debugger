async (page) => {
  const origin = 'http://127.0.0.1:12341'
  if (!page.url().startsWith(origin + '/')) throw new Error('Isolated operator gateway required')
  const checks = []
  const errors = []
  const check = (name, value) => { if (!value) throw new Error(name); checks.push({ name, passed: true }) }
  const until = async (test, name, timeout = 10000) => {
    const end = Date.now() + timeout
    while (Date.now() < end) { if (await test()) return; await page.waitForTimeout(50) }
    throw new Error('Timed out: ' + name)
  }
  const api = async path => {
    const response = await page.request.get(origin + path)
    if (!response.ok()) throw new Error(path + ': ' + response.status())
    return response.json()
  }
  const upstream = async () => (await page.request.get('http://127.0.0.1:28003/')).json()
  const history = (await api('/api/history?q=op-loop&limit=200')).items
  const failed = history.find(log => log.status === 'error' && !log.replay && log.summary.includes('op-loop-failure'))
  check('real failed Agent child is available', Boolean(failed?.correlation.parent_trace_id))
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(origin + '/ui/')
  page.on('pageerror', error => errors.push(String(error)))
  await page.getByTitle('qa-operator-main', { exact: true }).click()
  await page.getByRole('button', { name: '调用画布', exact: true }).click()
  const finder = page.getByRole('textbox', { name: '查找请求', exact: true })
  await finder.waitFor()
  await until(async () => await page.getByRole('button', { name: /^调用：/ }).count() >= 30, 'full Agent graph')
  const nodeCount = await page.getByRole('button', { name: /^调用：/ }).count()
  await finder.fill('op-loop-step-')
  await page.getByRole('combobox', { name: '请求排序', exact: true }).selectOption('duration-desc')
  const list = page.getByLabel('请求列表', { exact: true })
  check('duration sort finds the slower call', (await list.getByRole('button').first().innerText()).includes('op-loop-step-12'))
  await finder.fill('op-loop-failure')
  await page.getByRole('combobox', { name: '请求状态', exact: true }).selectOption('error')
  check('status and keyword find one failed call', await list.getByRole('button').count() === 1)
  check('list filtering preserves all graph nodes', await page.getByRole('button', { name: /^调用：/ }).count() === nodeCount)
  await list.getByRole('button').click()
  await page.getByRole('button', { name: '上下文变化', exact: true }).first().waitFor()
  await page.screenshot({ path: 'output/playwright/agent-debug-loop/failed-call.png', fullPage: true })
  await page.getByRole('button', { name: '上下文变化', exact: true }).first().click()
  const context = page.getByRole('region', { name: '相邻调用上下文对比' })
  await until(async () => (await context.innerText()).includes(failed.correlation.parent_trace_id.slice(0, 8)), 'captured parent comparison')
  check('context action uses the captured parent', (await context.innerText()).includes('父调用'))
  await page.getByRole('tab', { name: '重放', exact: true }).click()
  const bench = page.getByRole('region', { name: '请求重放工作台' })
  const editor = bench.getByRole('textbox', { name: '重放正文', exact: true })
  await editor.waitFor()
  const original = await editor.inputValue()
  check('source draft preserves the large integer', original.includes('9007199254740993'))
  const edited = original.replace('qa-failure', 'qa-corrected').replace('9007199254740993', '9007199254740995')
  await editor.fill(edited)
  await bench.getByText('编辑允许的请求头', { exact: true }).click()
  const headerEditor = bench.getByRole('textbox', { name: '重放请求头', exact: true })
  const headers = JSON.parse(await headerEditor.inputValue())
  headers['OpenAI-Beta'] = 'operator-qa'
  const editedHeaders = JSON.stringify(headers, null, 2)
  await headerEditor.fill(editedHeaders)
  const credential = bench.getByLabel(/请求头 Authorization/)
  await credential.fill('synthetic-loop-seed')
  await until(async () => (await bench.innerText()).includes('9007199254740995'), 'lossless edit difference')
  check('numeric edit shows both exact integer values', (await bench.innerText()).includes('9007199254740993') && (await bench.innerText()).includes('9007199254740995'))

  await page.getByRole('tab', { name: '上下文变化', exact: true }).click()
  await context.waitFor({ state: 'visible' })
  await page.getByRole('tab', { name: '重放', exact: true }).click()
  check('context visit preserves request and header drafts', await editor.inputValue() === edited && await headerEditor.inputValue() === editedHeaders)
  check('context visit preserves the transient credential', await credential.inputValue() === 'synthetic-loop-seed')
  await page.getByRole('button', { name: '调用画布', exact: true }).click()
  await page.getByRole('button', { name: /^返回重放工作台/ }).click()
  await bench.waitFor({ state: 'visible' })
  check('graph round trip keeps source draft and credential', await editor.inputValue() === edited && await credential.inputValue() === 'synthetic-loop-seed')

  const before = (await upstream()).count
  const run = bench.getByRole('button', { name: '发送修改后的请求', exact: true })
  await until(() => run.isEnabled(), 'validated replay ready')
  await run.click()
  await until(async () => (await bench.innerText()).includes('本次重放：已完成'), 'corrected replay')
  const replays = (await api('/api/replays')).filter(record => record.replay_of === failed.trace_id).sort((a, b) => b.created_at.localeCompare(a.created_at))
  const replay = replays[0]
  check('one correction executes one upstream request', (await upstream()).count === before + 1)
  check('corrected replay succeeds with provenance', replay?.state === 'done' && replay.modified && replay.source === 'outgoing')
  const capture = await api('/api/requests/' + replay.trace_id)
  check('edited numeric bytes reach the captured outgoing request', capture.outgoing.body.includes('9007199254740995') && !capture.outgoing.body.includes('9007199254740993'))
  await bench.getByRole('button', { name: '对比来源响应', exact: true }).click()
  const comparison = page.getByRole('region', { name: '重放结果评估' })
  await until(async () => (await comparison.innerText()).includes('qa-corrected'), 'readable result comparison')
  const comparisonText = await comparison.innerText()
  check('comparison shows failed source and successful result', comparisonText.includes('429') && comparisonText.includes('200') && comparisonText.includes('失败') && comparisonText.includes('已完成'))
  check('comparison includes truthful unknown and known token metrics', comparisonText.includes('未知') && comparisonText.includes('Provider usage') && comparisonText.includes('耗时与 Token'))
  check('normal JSON output is readable without opening raw files', comparisonText.includes('合成上游响应：') && comparisonText.includes('已观察输出'))
  await comparison.scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'output/playwright/agent-debug-loop/result-evaluation.png', fullPage: true })
  await bench.getByRole('button', { name: '查看新调用', exact: true }).click()
  const details = page.getByRole('region', { name: '响应与调用详情' })
  await details.waitFor()
  check('result details avoid an empty thinking pane', !(await details.innerText()).includes('No thinking content'))
  await page.getByRole('button', { name: '对比来源', exact: true }).first().click()
  await comparison.waitFor({ state: 'visible' })
  await page.getByRole('button', { name: /^返回重放工作台/ }).click()
  await bench.waitFor({ state: 'visible' })
  check('result round trip restores the same source editor', await editor.inputValue() === edited)
  check('navigation creates no additional model calls', (await upstream()).count === before + 1)

  // Preserve a real second-page history investigation across a details visit.
  await page.getByRole('button', { name: '管理', exact: true }).click()
  await page.getByRole('button', { name: '历史记录', exact: true }).click()
  const historyPanel = page.getByRole('region', { name: '历史查询与清理' })
  await historyPanel.getByRole('textbox', { name: '历史关键词' }).fill('op-loop')
  await historyPanel.getByRole('button', { name: '查询', exact: true }).click()
  await historyPanel.getByRole('button', { name: '下一页', exact: true }).click()
  await historyPanel.getByRole('button', { name: '返回第一页', exact: true }).waitFor()
  const rowText = await historyPanel.locator('article').first().innerText()
  await historyPanel.locator('article').first().getByRole('button', { name: '查看', exact: true }).click()
  await page.getByRole('button', { name: '返回历史查询', exact: true }).click()
  await historyPanel.waitFor({ state: 'visible' })
  check('history return retains the query and page', await historyPanel.getByRole('textbox', { name: '历史关键词' }).inputValue() === 'op-loop' && await historyPanel.getByRole('button', { name: '返回第一页', exact: true }).isVisible())
  check('history return retains the same result rows', (await historyPanel.locator('article').first().innerText()) === rowText)
  check('credentials never enter browser storage', !(await page.evaluate(() => JSON.stringify(Object.entries(localStorage)) + JSON.stringify(Object.entries(sessionStorage)))).includes('synthetic-loop-seed'))
  check('no uncaught browser errors', errors.length === 0)
  return { checks, errors, source_trace: failed.trace_id, replay_trace: replay.trace_id }
}
